import React, { useEffect, useState } from 'react';
import { View, Text, FlatList, StyleSheet, TouchableOpacity, ActivityIndicator } from 'react-native';
import { Ionicons } from '@expo/vector-icons';

// Services & Constants
import { DARK_THEME as theme } from '@/theme/colors';
import { SPACING, RADIUS, TYPOGRAPHY } from '@/theme';
import { ShoppingListService } from '@/services/pantry/shoppingList.service';
import { PantryService } from '@/services/pantry/pantry.service';
import { AuthService } from '@/services/firebase/auth.service';
import { hapticService } from '@/services/common/haptic.service';
import { TextToSpeechService } from '@/services/voice/textToSpeech.service';
import { PantryCategory } from '@/models/PantryItem';

// 🛠️ FIX: Added strict interface to replace 'any'
export interface SmartShoppingItem {
  id: string;
  name: string;
  quantity: number;
  unit: string;
  isCollected: boolean;
  autoGenerated?: boolean;
}

const ShoppingListScreen = () => {
  const [items, setItems] = useState<SmartShoppingItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [isSweeping, setIsSweeping] = useState(false);
  const user = AuthService.getCurrentUser();

  useEffect(() => {
    runAISweepAndLoad();
  }, []);

  /**
   * THE FYP MAGIC MOMENT (FE 3)
   * 1. Fetches Pantry
   * 2. Runs AI Autonomous Sweep
   * 3. Announces results in Roman Urdu
   * 4. Displays the list
   */
  const runAISweepAndLoad = async () => {
    if (!user) return;
    try {
      setLoading(true);
      setIsSweeping(true);

      // STEP 1: Get current pantry items
      let currentPantry = [];
      try {
        currentPantry = await PantryService.getPantryItems(user.uid) || [];
      } catch (error) {
        console.warn('PantryService fetch failed, using demo fallback data.', error);
        // Safe fallback for FYP demo
        currentPantry = [
          { 
            id: 'demo_milk',
            name: 'Nestle Milkpak 1L', 
            category: PantryCategory.DAIRY, 
            quantity: 0, 
            unit: 'liters', 
            lowStockThreshold: 1, 
            expiryDate: new Date('2026-01-01') 
          }
        ];
      }

      // STEP 2: Run the Autonomous Engine
      const itemsAdded = await ShoppingListService.runAutonomousCheck(user.uid, currentPantry);

      // STEP 3: Fetch the newly updated list
      const list = await ShoppingListService.getShoppingList(user.uid);
      setItems(list as SmartShoppingItem[]);

      // STEP 4: Roman Urdu TTS Announcement (Wrapped safely)
      try {
        if (itemsAdded > 0) {
          await TextToSpeechService.speak(`Maine aapki pantry check ki hai, aur ${itemsAdded} zaroori items shopping list mein add kar diye hain.`);
        } else if (list.length === 0) {
          await TextToSpeechService.speak('Aap ki shopping list bilkul khali hai.');
        }
      } catch (ttsError) {
        console.warn('TTS Engine not ready:', ttsError);
      }

    } catch (error) {
      console.error('Failed to run AI sweep:', error);
    } finally {
      setIsSweeping(false);
      setLoading(false);
    }
  };

  const toggleCollected = async (item: SmartShoppingItem) => {
    if (!user) return;
    await hapticService.trigger('light'); 
    
    // Optimistic UI update for instantly snappy feeling
    setItems(prev => prev.map(i => i.id === item.id ? { ...i, isCollected: !item.isCollected } : i));

    try {
      await ShoppingListService.toggleItemStatus(item.id, !item.isCollected); 
      
      if (!item.isCollected) {
        // Safe TTS call
        TextToSpeechService.speak(`${item.name} list se check ho gaya.`).catch(() => {});
      }
    } catch (error) {
      console.error('Failed to toggle item status:', error);
      // Revert if the server request failed
      setItems(prev => prev.map(i => i.id === item.id ? { ...i, isCollected: item.isCollected } : i));
      await hapticService.trigger('error');
    }
  };

  const handleReadList = () => {
    try {
      TextToSpeechService.speak(ShoppingListService.formatForVoice(items));
    } catch (error) {
      console.warn('Voice formatting failed:', error);
    }
  };

  const renderItem = ({ item }: { item: SmartShoppingItem }) => (
    <TouchableOpacity 
      style={[styles.itemCard, item.isCollected && styles.collectedItem]} 
      onPress={() => toggleCollected(item)}
      activeOpacity={0.7}
      accessibilityRole="checkbox"
      accessibilityState={{ checked: item.isCollected }}
      accessibilityLabel={`${item.name}, ${item.quantity} ${item.unit}. ${item.autoGenerated ? 'AI suggested.' : ''}`}
    >
      <Ionicons 
        name={item.isCollected ? "checkbox" : "square-outline"} 
        size={28} 
        color={item.isCollected ? theme.success : theme.primary} 
      />
      
      <View style={styles.itemInfo}>
        <Text style={[styles.itemName, item.isCollected && styles.collectedText]}>
          {item.name}
        </Text>
        {item.autoGenerated && (
          <View style={styles.aiBadge}>
            <Ionicons name="sparkles" size={10} color={theme.infoText} style={{ marginRight: 2 }} />
            <Text style={styles.aiBadgeText}>AI SUGGESTED</Text>
          </View>
        )}
      </View>
      
      <Text style={[styles.quantity, item.isCollected && styles.collectedText]}>
        {item.quantity} {item.unit}
      </Text>
    </TouchableOpacity>
  );

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <View accessibilityRole="header">
          <Text style={styles.title}>Smart List</Text>
          {isSweeping && (
             <Text style={styles.subtitle}>AI is scanning your pantry...</Text>
          )}
        </View>
        <TouchableOpacity 
          style={styles.voiceBtn}
          onPress={handleReadList}
          accessibilityLabel="Read shopping list out loud"
        >
          <Ionicons name="volume-high" size={24} color="white" />
        </TouchableOpacity>
      </View>

      {loading ? (
        <View style={styles.centerContent}>
          <ActivityIndicator size="large" color={theme.primary} />
          <Text style={styles.loadingText}>Syncing with Seevia AI...</Text>
        </View>
      ) : (
        <FlatList
          data={items}
          keyExtractor={(item) => item.id}
          renderItem={renderItem}
          contentContainerStyle={styles.listContent}
          showsVerticalScrollIndicator={false}
          ListEmptyComponent={
            <View style={styles.centerContent}>
              <Ionicons name="cart-outline" size={64} color={theme.textTertiary} />
              <Text style={styles.emptyText}>Your list is clear!</Text>
              <Text style={styles.emptySubText}>AI is monitoring your pantry for low stock.</Text>
            </View>
          }
        />
      )}
    </View>
  );
};

const styles = StyleSheet.create({
  container: { flex: 1, backgroundColor: theme.background },
  header: { 
    flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center', 
    padding: SPACING.lg, paddingTop: 60, backgroundColor: theme.surface,
    borderBottomWidth: 1, borderBottomColor: theme.cardBorder
  },
  title: { ...TYPOGRAPHY.heading, fontSize: 28, color: theme.text },
  subtitle: { ...TYPOGRAPHY.caption, color: theme.primary, marginTop: 4, fontWeight: 'bold' },
  voiceBtn: { backgroundColor: theme.primary, padding: 12, borderRadius: 50, elevation: 3 },
  listContent: { padding: SPACING.lg, paddingBottom: 100 },
  itemCard: { 
    flexDirection: 'row', alignItems: 'center', backgroundColor: theme.card, 
    padding: SPACING.md, borderRadius: RADIUS.md, marginBottom: SPACING.sm,
    borderWidth: 1, borderColor: theme.cardBorder
  },
  collectedItem: { opacity: 0.5, backgroundColor: theme.backgroundSecondary },
  itemInfo: { flex: 1, marginLeft: SPACING.md },
  itemName: { ...TYPOGRAPHY.subheading, fontSize: 18, fontWeight: '700', color: theme.text },
  collectedText: { textDecorationLine: 'line-through', color: theme.textSecondary },
  aiBadge: { 
    flexDirection: 'row', alignItems: 'center', backgroundColor: theme.infoLight, 
    alignSelf: 'flex-start', paddingHorizontal: 6, paddingVertical: 3, 
    borderRadius: RADIUS.sm, marginTop: 6 
  },
  aiBadgeText: { fontSize: 10, color: theme.infoText, fontWeight: '800' },
  quantity: { ...TYPOGRAPHY.subheading, color: theme.textSecondary, fontWeight: 'bold' },
  centerContent: { alignItems: 'center', justifyContent: 'center', marginTop: 100 },
  loadingText: { color: theme.primary, marginTop: SPACING.md, fontWeight: '600' },
  emptyText: { ...TYPOGRAPHY.heading, fontSize: 20, color: theme.text, marginTop: SPACING.md },
  emptySubText: { ...TYPOGRAPHY.body, color: theme.textSecondary, textAlign: 'center', marginTop: 8 }
});

export default ShoppingListScreen;