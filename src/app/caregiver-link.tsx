import React, { useState } from 'react';
import { View, Text, StyleSheet, Alert } from 'react-native';
import { useRouter } from 'expo-router';
import { Ionicons } from '@expo/vector-icons';

// Core UI Components
import ScreenLayout from '@/components/common/ScreenLayout';
import Button from '@/components/common/Button';
import Card from '@/components/common/Card';
import Input from '@/components/common/Input';

// Theme
import { DARK_THEME as theme } from '@/theme/colors';
import { SPACING, RADIUS, TYPOGRAPHY } from '@/theme';

// Services
import { AuthService } from '@/services/firebase/auth.service';
import { PWDConnectionService } from '@/services/firebase/pwdConnection.service';
import { hapticService } from '@/services/common/haptic.service';
// @ts-ignore
import TtsService from '@/services/voice/TtsService';
import { logger } from '@/utils/logger';

export default function CaregiverLinkScreen() {
  const router = useRouter();
  const [code, setCode] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState('');

  const handleLinkAccount = async () => {
    // 1. Basic Validation
    if (!code || code.trim().length < 6) {
      setErrorMessage('Please enter a valid 6-character code.');
      hapticService.trigger('error');
      TtsService.speak('Code galat hai. Cheh haraf ka code darj karein.');
      return;
    }

    const user = AuthService.getCurrentUser();
    if (!user) {
      setErrorMessage('You must be logged in to link an account.');
      return;
    }

    try {
      setIsLoading(true);
      setErrorMessage('');
      
      // We read the code aloud so the user knows the app is processing it
      TtsService.speak('Code verify kar raha hoon. Ek second rukiye.');

      // 2. The Handshake (Calls your exact service method)
      const caregiverName = user.displayName || 'Seevia Caregiver';
      const connection = await PWDConnectionService.validateAndUseCode(code, user.uid, caregiverName);

      // 3. Success Handling
      hapticService.trigger('success');
      TtsService.speak(`Mubarak ho! Aap ${connection.pwd_name} ke account ke sath link ho gaye hain.`);
      
      Alert.alert(
        "Connection Successful!", 
        `You are now linked to ${connection.pwd_name}.`,
        [{ text: "Continue", onPress: () => router.replace('/(tabs)/home') }]
      );

    } catch (error: any) {
      // 4. Error Handling (Expired, Used, or Invalid Code)
      logger.error('CAREGIVER_LINK', 'Failed to link account', error);
      setErrorMessage(error.message || 'Invalid or expired invitation code.');
      hapticService.trigger('heavy');
      TtsService.speak('Yeh code kaam nahi kar raha. Dobara check karein.');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <ScreenLayout scrollable={true} padding={true}>
      <View style={styles.header}>
        <Ionicons name="link" size={40} color={theme.primary} style={styles.headerIcon} />
        <Text style={[styles.title, { color: theme.text }]}>Link PWD Account</Text>
        <Text style={[styles.subtitle, { color: theme.textSecondary }]}>
          Enter the 6-digit invitation code generated by the visually impaired user's device.
        </Text>
      </View>

      <Card style={styles.card}>
        <Input
          label="Invitation Code"
          placeholder="e.g. SEE786"
          value={code}
          onChangeText={(text) => {
            setCode(text.toUpperCase());
            setErrorMessage(''); // Clear errors when typing
          }}
          maxLength={6}
          autoCapitalize="characters"
          icon="key-outline"
        />

        {errorMessage ? (
          <View style={[styles.errorBox, { backgroundColor: `${theme.danger}22` }]}>
            <Ionicons name="warning" size={20} color={theme.danger} />
            <Text style={[styles.errorText, { color: theme.danger }]}>{errorMessage}</Text>
          </View>
        ) : null}

        <Button 
          title="Connect Account" 
          onPress={handleLinkAccount} 
          loading={isLoading} 
          disabled={code.length < 6}
          fullWidth 
          style={styles.submitBtn} 
        />
      </Card>

      <View style={styles.helpSection}>
        <Text style={[styles.helpTitle, { color: theme.text }]}>Where is my code?</Text>
        <Text style={[styles.helpText, { color: theme.textSecondary }]}>
          The visually impaired user needs to open their Seevia app, go to Settings, and tap "Generate Invite Code".
        </Text>
      </View>

      <Button 
        title="Cancel" 
        onPress={() => router.back()} 
        variant="outline" 
        fullWidth 
        style={styles.cancelBtn} 
      />
    </ScreenLayout>
  );
}

const styles = StyleSheet.create({
  header: {
    alignItems: 'center',
    marginVertical: SPACING.xl,
    paddingHorizontal: SPACING.lg,
  },
  headerIcon: {
    marginBottom: SPACING.sm,
  },
  title: {
    ...TYPOGRAPHY.heading,
    fontSize: 28,
    textAlign: 'center',
    marginBottom: SPACING.xs,
  },
  subtitle: {
    ...TYPOGRAPHY.body,
    textAlign: 'center',
    lineHeight: 22,
  },
  card: {
    padding: SPACING.xl,
    marginBottom: SPACING.xl,
  },
  submitBtn: {
    marginTop: SPACING.lg,
  },
  errorBox: {
    flexDirection: 'row',
    alignItems: 'center',
    padding: SPACING.md,
    borderRadius: RADIUS.md,
    marginTop: SPACING.sm,
    gap: SPACING.sm,
  },
  errorText: {
    flex: 1,
    fontSize: 14,
    fontWeight: '600',
  },
  helpSection: {
    paddingHorizontal: SPACING.lg,
    alignItems: 'center',
  },
  helpTitle: {
    fontWeight: '700',
    fontSize: 16,
    marginBottom: 4,
  },
  helpText: {
    textAlign: 'center',
    fontSize: 14,
    lineHeight: 20,
  },
  cancelBtn: {
    marginTop: SPACING.xl,
  }
});