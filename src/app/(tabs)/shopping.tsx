/**
 * Seevia Shopping Tab — FULLY FUNCTIONAL
 * Voice-first: shopping list + guided mode + store navigation + product scan
 */
import React, { useState, useCallback, useEffect, useMemo, useRef } from 'react';
import {
  View, Text, StyleSheet, FlatList, TouchableOpacity,
  ActivityIndicator, TextInput, DeviceEventEmitter, Vibration,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useRouter, useFocusEffect } from 'expo-router';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { DARK_THEME as theme } from '@/theme/colors';
import { SPACING, RADIUS } from '@/theme';
import { hapticService } from '@/services/common/haptic.service';
// @ts-ignore
import TtsService from '@/services/voice/TtsService';
import { AuthService } from '@/services/firebase/auth.service';
import { PantryService } from '@/services/pantry/pantry.service';
import { ShoppingListService } from '@/services/pantry/shoppingList.service';

export interface ShoppingItem {
  id: string;
  name: string;
  quantity: number;
  checked: boolean;
  unit?: string;
  autoGenerated?: boolean;
}

export default function ShoppingTab() {
  const router = useRouter();
  const insets = useSafeAreaInsets();

  const [shoppingItems, setShoppingItems] = useState<ShoppingItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [destination, setDestination] = useState('');
  const [navigating, setNavigating] = useState(false);
  const [listRead, setListRead] = useState(false);
  const [guidedMode, setGuidedMode] = useState(false);
  const [guidedIndex, setGuidedIndex] = useState(0);
  const guidedRef = useRef<ShoppingItem[]>([]);

  useFocusEffect(
    useCallback(() => {
      setListRead(false);
      loadShoppingList();
    }, [])
  );

  // Auto-read list when loaded
  useEffect(() => {
    if (!loading && shoppingItems.length > 0 && !listRead) {
      const unchecked = shoppingItems.filter(i => !i.checked);
      if (unchecked.length > 0) {
        const names = unchecked.slice(0, 4).map(i => i.name).join(', ');
        setTimeout(() => TtsService.speak(
          `Shopping list mein ${unchecked.length} items hain: ${names}.`
        ), 600);
      } else {
        setTimeout(() => TtsService.speak('Aapki shopping list complete hai. Barakallah!'), 600);
      }
      setListRead(true);
    }
  }, [loading, shoppingItems, listRead]);

  // Listen for voice-triggered events
  useEffect(() => {
    const navSub = DeviceEventEmitter.addListener('NAVIGATE_EXTERNAL', (dest: string) => {
      setDestination(dest);
      router.push({ pathname: '/store-navigation', params: { target: dest, mode: 'outdoor' } });
    });

    const shopSub = DeviceEventEmitter.addListener('START_GUIDED_SHOPPING', () => {
      startGuidedShopping();
    });

    const findSub = DeviceEventEmitter.addListener('START_INDOOR_NAV', (product: string) => {
      router.push({ pathname: '/store-navigation', params: { target: product, mode: 'indoor' } });
    });

    return () => {
      navSub.remove();
      shopSub.remove();
      findSub.remove();
    };
  }, [shoppingItems]);

  const loadShoppingList = async () => {
    setLoading(true);
    try {
      const user = AuthService.getCurrentUser();
      if (!user) return;

      // Try Firebase first
      try {
        const list = await ShoppingListService.getShoppingList(user.uid);
        if (list && list.length > 0) {
          setShoppingItems(list.map(i => ({
            id: i.id,
            name: i.name || 'Item',
            quantity: i.quantity || 1,
            checked: i.isCollected || false,
            unit: i.unit,
            autoGenerated: i.autoGenerated,
          })));
          return;
        }
      } catch { /* fall through */ }

      // Fallback: generate from low pantry stock
      const pantryItems = await PantryService.getPantryItems(user.uid);
      const lowStock = pantryItems.filter(i => i.quantity <= (i.lowStockThreshold || 1));
      setShoppingItems(lowStock.map(i => ({
        id: i.id,
        name: i.name,
        quantity: Math.max(1, (i.lowStockThreshold || 1) - i.quantity + 1),
        checked: false,
        unit: i.unit,
        autoGenerated: true,
      })));
    } catch (e) {
      console.warn('[SHOPPING] Error:', e);
    } finally {
      setLoading(false);
    }
  };

  const startGuidedShopping = () => {
    const unchecked = shoppingItems.filter(i => !i.checked);
    if (unchecked.length === 0) {
      TtsService.speak('Shopping list khaali hai ya sab items collect ho gaye hain. Shaabaash!');
      return;
    }
    guidedRef.current = unchecked;
    setGuidedMode(true);
    setGuidedIndex(0);
    const first = unchecked[0];
    TtsService.speak(
      `Guided shopping shuru. ${unchecked.length} items dhoondhne hain. Pehla item: ${first.name}, ${first.quantity} ${first.unit || ''}. Store mein navigate kar raha hoon.`
    );
    setTimeout(() => {
      DeviceEventEmitter.emit('START_INDOOR_NAV', first.name);
    }, 4000);
  };

  const nextGuidedItem = async () => {
    const next = guidedIndex + 1;
    if (next >= guidedRef.current.length) {
      setGuidedMode(false);
      TtsService.speak('Mubarak ho! Saari shopping complete ho gayi. Ghar wapas jao.');
      hapticService.trigger('success');
      return;
    }
    const item = guidedRef.current[next];
    setGuidedIndex(next);
    await hapticService.trigger('light');
    TtsService.speak(`Acha! Ab ${item.name} dhoondhte hain — ${item.quantity} ${item.unit || ''}.`);
    setTimeout(() => DeviceEventEmitter.emit('START_INDOOR_NAV', item.name), 3000);
  };

  const toggleItem = async (item: ShoppingItem) => {
    await hapticService.trigger('light');
    const newChecked = !item.checked;
    setShoppingItems(prev => prev.map(i => i.id === item.id ? { ...i, checked: newChecked } : i));
    if (newChecked) {
      TtsService.speak(`${item.name} list se check ho gaya.`);
      Vibration.vibrate([0, 80, 80, 80]);
      try {
        await ShoppingListService.toggleItemStatus(item.id, true);
      } catch { /* offline-safe */ }
      // In guided mode, advance automatically
      if (guidedMode) {
        setTimeout(() => nextGuidedItem(), 1500);
      }
    }
  };

  const clearCompleted = async () => {
    await hapticService.trigger('medium');
    setShoppingItems(prev => prev.filter(i => !i.checked));
    TtsService.speak('Purchased items clear ho gaye.');
  };

  const readFullList = () => {
    const unchecked = shoppingItems.filter(i => !i.checked);
    if (unchecked.length === 0) {
      TtsService.speak('Aapki shopping list complete hai.');
    } else {
      const names = unchecked.map(i => `${i.name} — ${i.quantity} ${i.unit || ''}`).join('. ');
      TtsService.speak(`${unchecked.length} items baki hain: ${names}.`);
    }
  };

  const { unchecked, checked } = useMemo(() => ({
    unchecked: shoppingItems.filter(i => !i.checked),
    checked: shoppingItems.filter(i => i.checked),
  }), [shoppingItems]);

  return (
    <View style={[styles.container, { backgroundColor: theme.background, paddingTop: insets.top }]}>

      {/* Header */}
      <View style={styles.header}>
        <View accessibilityRole="header">
          <Text style={[styles.title, { color: theme.text }]}>Shopping</Text>
          <Text style={[styles.subtitle, { color: theme.textSecondary }]}>
            {unchecked.length} items remaining
          </Text>
        </View>
        <View style={styles.headerBtns}>
          <TouchableOpacity
            style={[styles.iconBtn, { backgroundColor: `${theme.primary}22` }]}
            onPress={readFullList}
            accessibilityLabel="Read full shopping list aloud"
          >
            <Ionicons name="volume-high" size={20} color={theme.primary} />
          </TouchableOpacity>
          <TouchableOpacity
            style={[styles.iconBtn, { backgroundColor: theme.primary }]}
            onPress={() => router.push('/scanner')}
            accessibilityLabel="Scan product barcode"
          >
            <Ionicons name="barcode-outline" size={20} color="#FFF" />
          </TouchableOpacity>
        </View>
      </View>

      {/* Guided Shopping Banner */}
      {guidedMode && guidedRef.current[guidedIndex] && (
        <TouchableOpacity
          style={[styles.guidedBanner, { backgroundColor: theme.primary }]}
          onPress={nextGuidedItem}
          accessibilityLabel="Mark as collected and go to next item"
        >
          <Ionicons name="navigate-circle" size={22} color="#FFF" />
          <View style={{ flex: 1 }}>
            <Text style={styles.guidedLabel}>GUIDED MODE — Item {guidedIndex + 1}/{guidedRef.current.length}</Text>
            <Text style={styles.guidedItem}>{guidedRef.current[guidedIndex]?.name}</Text>
          </View>
          <Ionicons name="checkmark-circle-outline" size={24} color="#FFF" />
        </TouchableOpacity>
      )}

      {/* Navigation Section */}
      <View style={[styles.navSection, { backgroundColor: theme.card, borderColor: theme.cardBorder }]}>
        <Text style={[styles.navLabel, { color: theme.textSecondary }]}>Navigate to Store</Text>
        <View style={styles.navRow}>
          <TextInput
            style={[styles.navInput, { color: theme.text, backgroundColor: theme.backgroundSecondary }]}
            placeholder="Type destination..."
            placeholderTextColor={theme.textTertiary}
            value={destination}
            onChangeText={setDestination}
            onSubmitEditing={() => {
              if (destination.trim()) {
                router.push({ pathname: '/store-navigation', params: { target: destination.trim(), mode: 'outdoor' } });
              }
            }}
            accessibilityLabel="Store destination input"
          />
          <TouchableOpacity
            style={[styles.navBtn, { backgroundColor: theme.primary }]}
            onPress={() => {
              const t = destination.trim() || 'Store';
              router.push({ pathname: '/store-navigation', params: { target: t, mode: 'outdoor' } });
            }}
            accessibilityLabel="Start Navigation"
          >
            {navigating
              ? <ActivityIndicator size="small" color="#FFF" />
              : <Ionicons name="navigate" size={22} color="#FFF" />
            }
          </TouchableOpacity>
        </View>

        {/* Quick Destinations */}
        <View style={styles.quickDestRow}>
          {['Carrefour', 'Makro', 'CSD', 'Giga Mall'].map((d) => (
            <TouchableOpacity
              key={d}
              style={[styles.quickDest, { backgroundColor: theme.backgroundSecondary, borderColor: theme.cardBorder }]}
              onPress={() => {
                TtsService.speak(`${d} ka rasta khol raha hoon.`);
                router.push({ pathname: '/store-navigation', params: { target: d, mode: 'outdoor' } });
              }}
              accessibilityLabel={`Navigate to ${d}`}
            >
              <Text style={[styles.quickDestText, { color: theme.text }]}>{d}</Text>
            </TouchableOpacity>
          ))}
        </View>
      </View>

      {/* Guided Shopping Button */}
      {!guidedMode && unchecked.length > 0 && (
        <TouchableOpacity
          style={[styles.guidedStartBtn, { backgroundColor: `${theme.success}18`, borderColor: theme.success }]}
          onPress={startGuidedShopping}
          accessibilityLabel="Start guided shopping mode"
        >
          <Ionicons name="walk-outline" size={20} color={theme.success} />
          <Text style={[styles.guidedStartText, { color: theme.success }]}>
            Start Guided Shopping ({unchecked.length} items)
          </Text>
        </TouchableOpacity>
      )}

      {/* Shopping List */}
      {loading ? (
        <View style={styles.center}>
          <ActivityIndicator size="large" color={theme.primary} />
          <Text style={[styles.loadingText, { color: theme.primary }]}>Loading list...</Text>
        </View>
      ) : (
        <FlatList
          data={[...unchecked, ...checked]}
          keyExtractor={i => i.id}
          contentContainerStyle={styles.listContent}
          showsVerticalScrollIndicator={false}
          ListEmptyComponent={
            <View style={styles.center}>
              <Ionicons name="cart-outline" size={60} color={theme.textTertiary} />
              <Text style={[styles.emptyText, { color: theme.textSecondary }]}>
                Shopping list khali hai.{'\n'}Pantry scan se items auto-add honge.
              </Text>
              <TouchableOpacity
                style={[styles.reloadBtn, { borderColor: theme.primary }]}
                onPress={loadShoppingList}
                accessibilityLabel="Reload shopping list"
              >
                <Ionicons name="refresh" size={18} color={theme.primary} />
                <Text style={[styles.reloadText, { color: theme.primary }]}>Reload</Text>
              </TouchableOpacity>
            </View>
          }
          renderItem={({ item }) => (
            <TouchableOpacity
              style={[styles.listItem, {
                backgroundColor: theme.card,
                borderColor: item.checked ? theme.success : (guidedMode && guidedRef.current[guidedIndex]?.id === item.id ? theme.primary : theme.cardBorder),
                borderWidth: guidedMode && guidedRef.current[guidedIndex]?.id === item.id ? 2 : 1,
                opacity: item.checked ? 0.55 : 1,
              }]}
              onPress={() => toggleItem(item)}
              accessibilityRole="checkbox"
              accessibilityState={{ checked: item.checked }}
              accessibilityLabel={`${item.name}, ${item.quantity} ${item.unit || ''}. ${item.autoGenerated ? 'AI suggested.' : ''}`}
            >
              <View style={[styles.checkCircle, {
                borderColor: item.checked ? theme.success : theme.textTertiary,
                backgroundColor: item.checked ? theme.success : 'transparent',
              }]}>
                {item.checked && <Ionicons name="checkmark" size={16} color="#FFF" />}
              </View>

              <View style={styles.itemInfo}>
                <Text style={[styles.itemName, { color: theme.text, textDecorationLine: item.checked ? 'line-through' : 'none' }]}>
                  {item.name}
                </Text>
                <Text style={[styles.itemQty, { color: theme.textSecondary }]}>
                  Qty: {item.quantity} {item.unit || 'pcs'}{item.autoGenerated ? ' · AI' : ''}
                </Text>
              </View>

              <TouchableOpacity
                onPress={() => {
                  TtsService.speak(`${item.name} scan kar raha hoon.`);
                  router.push('/scanner');
                }}
                accessibilityLabel={`Scan ${item.name}`}
                style={styles.scanIconBtn}
              >
                <Ionicons name="scan-circle" size={32} color={theme.primary} />
              </TouchableOpacity>
            </TouchableOpacity>
          )}
          ListFooterComponent={
            <View style={{ gap: SPACING.md, marginTop: SPACING.md }}>
              <TouchableOpacity
                style={[styles.actionBtn, { borderColor: theme.primary, borderStyle: 'dashed' }]}
                onPress={() => router.push('/add-item')}
                accessibilityLabel="Add item manually"
              >
                <Ionicons name="add" size={20} color={theme.primary} />
                <Text style={[styles.actionBtnText, { color: theme.primary }]}>Add Item Manually</Text>
              </TouchableOpacity>

              {checked.length > 0 && (
                <TouchableOpacity
                  style={[styles.actionBtn, { borderColor: theme.danger, backgroundColor: `${theme.danger}11` }]}
                  onPress={clearCompleted}
                  accessibilityLabel="Clear purchased items"
                >
                  <Ionicons name="trash-outline" size={18} color={theme.danger} />
                  <Text style={[styles.actionBtnText, { color: theme.danger }]}>Clear {checked.length} Purchased</Text>
                </TouchableOpacity>
              )}
            </View>
          }
        />
      )}

      {/* Bottom Voice Hint */}
      <View style={[styles.voiceHint, { backgroundColor: theme.backgroundSecondary }]}>
        <Ionicons name="mic-outline" size={16} color={theme.textTertiary} />
        <Text style={[styles.voiceHintText, { color: theme.textTertiary }]}>
          "Giga Mall le jao" · "Shopping list dikhao" · "Guided shopping shuru"
        </Text>
      </View>
    </View>
  );
}

